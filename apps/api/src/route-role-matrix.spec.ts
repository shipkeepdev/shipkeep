import { ModulesContainer, Reflector } from '@nestjs/core';
import { Test } from '@nestjs/testing';
import { allowsTenantAction } from '@shipkeep/domain';

import { AppModule } from './app.module';
import { type RouteRow, routeInventory } from './testing/route-inventory';
import {
  type TenantActor,
  tenantActors,
  type TenantIds,
  tenantPersona,
  tenantTarget,
} from './testing/tenant-personas';

const ids: TenantIds = {
  organizationId: '019d0000-0000-7000-8000-00000000000a',
  projectId: '019d0000-0000-7000-8000-00000000000b',
  environmentId: '019d0000-0000-7000-8000-00000000000c',
};
const members: readonly TenantActor[] = tenantActors.filter((actor) => actor !== 'outsider');
const projectReaders: readonly TenantActor[] = members.filter((actor) => actor !== 'member');
const projectAdmins: readonly TenantActor[] = ['owner', 'admin', 'projectAdmin', 'restrictedAdmin'];

/**
 * SPEC 7, written independently of the policy code: who may use each `permission@scope` that a
 * registered route declares. A new route with an unlisted pair fails until it is reviewed here.
 */
const SPEC_7: Readonly<Partial<Record<string, readonly TenantActor[]>>> = {
  'organization.read@organization': members,
  'organization.update@organization': ['owner', 'admin'],
  'project.create@organization': ['owner', 'admin'],
  'member.manage@organization': ['owner', 'admin'],
  'node.manage@organization': ['owner', 'admin'],
  'audit.read@organization': ['owner', 'admin'],
  // Fixture environments are protected: developers may not write their secrets (SPEC 7).
  'secret.write@environment': ['owner', 'admin', 'projectAdmin', 'environmentAdmin'],
  'deploy.run@environment': ['owner', 'admin', 'projectAdmin', 'environmentAdmin'],
  // An environment grant permits navigation to its parent project.
  'project.read@project': projectReaders,
  'project.update@project': projectAdmins,
  'environment.create@project': projectAdmins,
  'member.manage@project': projectAdmins,
  // restrictedAdmin is narrowed to viewer inside the environment.
  'environment.read@environment': projectReaders,
  'environment.update@environment': ['owner', 'admin', 'projectAdmin', 'environmentAdmin'],
  'member.manage@environment': ['owner', 'admin', 'projectAdmin', 'environmentAdmin'],
};

function decision(route: RouteRow, actor: TenantActor): boolean {
  if (route.access?.kind !== 'tenant') throw new Error(`${route.path} is not a tenant route`);
  return allowsTenantAction(
    tenantPersona(actor, ids),
    route.access.permission,
    tenantTarget(route.access.scope, ids),
  );
}

function markdown(routes: readonly RouteRow[]): string {
  const access = (route: RouteRow) =>
    route.anonymous
      ? 'anonymous'
      : route.access?.kind === 'tenant'
        ? `${route.access.permission} @ ${route.access.scope}`
        : (route.access?.kind ?? 'undeclared');
  const lines = [
    '# Route and role matrix',
    '',
    'Generated by `apps/api/src/route-role-matrix.spec.ts` from the registered routes and the',
    'domain policy. Do not edit by hand: run the API unit tests with `-u` and review the diff.',
    '',
    '`yes`/`no`: decision for a session of that actor. Bearer: permission a scoped API token needs',
    '(`-`: sessions only).',
    '',
    `| Method | Path | Access | Bearer | ${tenantActors.join(' | ')} |`,
    `| --- | --- | --- | --- |${' --- |'.repeat(tenantActors.length)}`,
  ];
  for (const route of routes) {
    const cells =
      route.access?.kind === 'tenant'
        ? tenantActors.map((actor) => (decision(route, actor) ? 'yes' : 'no'))
        : tenantActors.map(() => '');
    lines.push(
      `| ${route.method} | \`${route.path}\` | ${access(route)} | ${route.bearer ?? '-'} | ${cells.join(' | ')} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

describe('route and role matrix', () => {
  let routes: RouteRow[];

  beforeAll(async () => {
    // Compiling registers every controller; no lifecycle hook runs, so nothing connects.
    const moduleRef = await Test.createTestingModule({ imports: [AppModule] }).compile();
    routes = routeInventory(moduleRef.get(ModulesContainer), moduleRef.get(Reflector));
    await moduleRef.close();
  });

  it('matches SPEC 7 for every registered tenant route and actor', () => {
    const tenant = routes.filter((route) => route.access?.kind === 'tenant');
    expect(tenant.length).toBeGreaterThan(15);
    for (const route of tenant) {
      if (route.access?.kind !== 'tenant') continue;
      const key = `${route.access.permission}@${route.access.scope}`;
      const allowed = SPEC_7[key];
      expect(allowed, `${route.method} ${route.path}: review ${key} against SPEC 7`).toBeDefined();
      for (const actor of tenantActors)
        expect(decision(route, actor), `${route.method} ${route.path} as ${actor}`).toBe(
          allowed?.includes(actor) ?? false,
        );
    }
  });

  it('opts bearer tokens in only with the route permission, never on privilege changes', () => {
    for (const route of routes) {
      if (route.bearer === undefined) continue;
      expect(route.anonymous, route.path).toBe(false);
      if (route.access?.kind === 'tenant')
        expect(route.bearer, route.path).toBe(route.access.permission);
      else expect(route.bearer, route.path).toBe('profile.read');
      expect(route.path, route.path).not.toMatch(/\/(members|bindings|api-tokens)(\/|$)/);
    }
  });

  it('keeps the generated matrix document current', async () => {
    await expect(markdown(routes)).toMatchFileSnapshot(
      '../../../docs/generated/route-role-matrix.md',
    );
  });
});
