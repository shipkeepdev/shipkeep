export class NewResourcePage {
  private readonly api = inject(WorkspaceApi);
  private readonly shell = inject(ShellContext);
  private readonly router = inject(Router);
  private readonly i18n = inject(I18n);
  protected readonly notice = inject(Notice);
  protected readonly organizationId = computed(() => this.shell.organizationId() ?? '');
  protected readonly total = APPS.length + DATABASES.length + 388;
  protected readonly query = signal('');
  protected readonly category = signal('all');
  protected readonly categories = [
    { k: 'all', label: 'All' },
    { k: 'apps', label: 'Applications' },
    { k: 'dbs', label: 'Databases' },
    { k: 'svc', label: 'Services' },
  ];
  protected readonly hero = [
    {
      icon: 'file-code' as IconName,
      title: 'From a shipkeep.yml',
      desc: 'Paste the file: Shipkeep creates the application with its domains and secrets.',
      cta: 'Paste the file',
      border: 'rgba(255,92,92,0.35)',
      ready: true,
    },
    {
      icon: 'transfer-in' as IconName,
      title: 'Import from Coolify',
      desc: 'A whole instance or a project: apps, databases, variables and domains.',
      cta: 'Import',
      border: '#1C1C1E',
      ready: false,
    },
  ];
  private readonly params = toSignal(inject(ActivatedRoute).queryParamMap, { requireSync: true });
  private readonly environments = signal<readonly (Environment & { readonly project: string })[]>(
    [],
  );
  protected readonly targets = computed(() =>
    this.environments().map((e) => ({
      key: `${e.projectId}/${e.id}`,
      label: `${e.project} · ${e.name}`,
    })),
  );
  protected readonly targetKey = computed(() => {
    const project = this.params().get('project');
    const environment = this.params().get('environment');
    const wanted = project && environment ? `${project}/${environment}` : null;
    return this.targets().find((t) => t.key === wanted)?.key ?? this.targets().at(0)?.key ?? '';
  });
  protected readonly groups = computed(() => {
    const q = this.query().trim().toLowerCase();
    const match = (item: Item) =>
      !q ||
      [item.name, item.sub, item.desc]
        .map((s) => this.i18n.t(s))
        .join(' ')
        .toLowerCase()
        .includes(q);
    return [
      {
        k: 'apps',
        title: 'Applications',
        icon: 'apps' as IconName,
        note: 'From a source',
        items: APPS.filter(match),
      },
      {
        k: 'dbs',
        title: 'Databases',
        icon: 'database' as IconName,
        note: 'Backups to your S3, confirmed restore',
        items: DATABASES.filter(match),
      },
      {
        k: 'svc',
        title: 'One-click services',
        icon: 'stack-2' as IconName,
        note: '388 templates · 24 shown',
        items: SERVICES.filter(match),
      },
    ].filter((g) => (this.category() === 'all' || this.category() === g.k) && g.items.length);
  });

  constructor() {
    effect(() => {
      const id = this.organizationId();
      const projects = this.shell.projects();
      if (!id) return;
      void Promise.all(
        projects.map(async (p) =>
          (await this.api.environments(id, p.id).catch(() => [])).map((e) => ({
            ...e,
            project: p.name,
          })),
        ),
      ).then((lists) => {
        this.environments.set(lists.flat());
      });
    });
  }

  protected choose(key: string): void {
    const [project, environment] = key.split('/');
    void this.router.navigate([], { queryParams: { project, environment }, replaceUrl: true });
  }

  /** Image applications and shipkeep.yml files are created from the environment's Resources tab. */
  protected openForm(): void {
    const [project, environment] = this.targetKey().split('/');
    if (!project || !environment) {
      this.notice.show('Create a project and an environment first.');
      return;
    }
    void this.router.navigate(
      ['/orgs', this.organizationId(), 'projects', project, 'environments', environment],
      {
        queryParams: { tab: 'applications' },
        fragment: 'applications-create-title',
      },
    );
  }
}
