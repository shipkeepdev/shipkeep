// The CLI reference of the documentation site (ADR 0027) is the help that each command prints,
// so it cannot drift from the flags: this test writes it with SHIPKEEP_UPDATE_REFERENCE=1 (`pnpm
// gen`), and otherwise fails when the committed page is not what the CLI says.
var referencePage = filepath.Join("..", "..", "..", "apps", "docs", "src", "content", "docs", "reference", "cli.md")

// Values that let a command reach its flags: a positional argument is checked before them.
var referenceArgs = map[string]string{
	"NAME":      "NAME",
	"SERVER_ID": "0190f5a8-7b1c-7e2d-8f3a-0123456789ab",
}

const referenceIntro = `---
title: CLI
description: Every command of the shipkeep CLI and its flags, as the CLI itself prints them.
tableOfContents:
  maxHeadingLevel: 2
---

<!-- Generated by cli/internal/commands/reference_test.go from the CLI's own help. Do not edit: run ` + "`pnpm gen`" + `. -->

` + "`shipkeep`" + ` is a single static binary for Linux, macOS and Windows, on amd64 and arm64. Each [release](https://github.com/shipkeepdev/shipkeep/releases) attaches it as ` + "`shipkeep_<version>_<os>_<arch>`" + `. It talks to the control plane's API with an API token.

- The token is read from a prompt or from standard input, never from a flag: a flag would land in the shell history and the process list.
- ` + "`login`" + ` saves the address and the token in a file only you can read. ` + "`SHIPKEEP_URL`" + ` and ` + "`SHIPKEEP_TOKEN`" + ` replace the saved login, for automation.
- Commands that reach an environment take ` + "`--org`, `--project` and `--env`" + `, or ` + "`SHIPKEEP_ORG`, `SHIPKEEP_PROJECT` and `SHIPKEEP_ENV`" + `. Each is an identifier, which the environment's address in the web UI shows: ` + "`/orgs/<organization>/projects/<project>/environments/<environment>`" + `.
- A flag takes one or two dashes. A misplaced flag or an extra argument is refused, never ignored.
- The exit status is 0 on success, 1 when the command failed, and 2 when it was not understood.
`

func TestReferencePageIsCurrent(t *testing.T) {
	var page strings.Builder
	page.WriteString(referenceIntro)
	for _, command := range Commands {
		page.WriteString(referenceSection(t, command))
	}
	if os.Getenv("SHIPKEEP_UPDATE_REFERENCE") == "1" {
		if err := os.WriteFile(referencePage, []byte(page.String()), 0o644); err != nil { //nolint:gosec // a documentation page, read by everyone
			t.Fatal(err)
		}
		return
	}
	current, err := os.ReadFile(referencePage)
	if err != nil {
		t.Fatal(err)
	}
	if string(current) != page.String() {
		t.Fatalf("%s is not what the CLI prints: run pnpm gen", referencePage)
	}
}

// referenceSection runs the command with -h, without any variable set, and keeps its flags.
func referenceSection(t *testing.T, command Command) string {
	t.Helper()
	errOut := &bytes.Buffer{}
	app := &App{
		In:              strings.NewReader(""),
		Out:             &bytes.Buffer{},
		Err:             errOut,
		Getenv:          func(string) string { return "" },
		CredentialsPath: func() (string, error) { return filepath.Join(t.TempDir(), "credentials.json"), nil },
		ReadSecret:      func(string) (string, error) { return "", nil },
	}
	args := strings.Fields(command.Name)
	for _, name := range strings.Fields(command.Args) {
		args = append(args, referenceArgs[name])
	}
	if status := app.Run(context.Background(), append(args, "-h")); status != 2 {
		t.Fatalf("shipkeep %s -h exited %d", command.Name, status)
	}
	help := strings.TrimPrefix(errOut.String(), fmt.Sprintf("Usage of shipkeep %s:\n", command.Name))
	if help == errOut.String() {
		t.Fatalf("shipkeep %s -h printed no flags: %q", command.Name, errOut.String())
	}
	synopsis := strings.Join(strings.Fields("shipkeep "+command.Name+" "+command.Args), " ")
	if help == "" {
		return fmt.Sprintf("\n## `shipkeep %s`\n\n%s. It takes no flag.\n\n```text\n%s\n```\n", command.Name, command.Summary, synopsis)
	}
	// Go prints flags with one dash, and a tab before their description.
	help = strings.ReplaceAll("\n"+help, "\n  -", "\n  --")[1:]
	help = strings.ReplaceAll(help, "    \t", "      ")
	return fmt.Sprintf("\n## `shipkeep %s`\n\n%s.\n\n```text\n%s [flags]\n\n%s```\n", command.Name, command.Summary, synopsis, help)
}
