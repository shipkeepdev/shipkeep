// Generates TypeScript artifacts from packages/config-schema/shipkeep.schema.json.
// Run through `pnpm gen`. Output is committed and never edited by hand (CLAUDE.md, rule 9).
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const schemaPath = join(root, 'packages', 'config-schema', 'shipkeep.schema.json');
const outDir = join(root, 'packages', 'config-schema', 'src', 'gen');

const header = `// Code generated by tools/gen/config-schema.mjs from shipkeep.schema.json. DO NOT EDIT.
/* eslint-disable */
`;

const schemaText = await readFile(schemaPath, 'utf8');
const schema = JSON.parse(schemaText);

// Conditional keywords (oneOf, allOf, if/then/else, not) express validation rules, not shape.
// json-schema-to-typescript turns them into unions and index signatures that only blur the types,
// so the type generator sees the schema without them. Validation always runs against the full schema.
const SHAPE_ONLY = new Set(['oneOf', 'allOf', 'anyOf', 'if', 'then', 'else', 'not']);
function shapeOnly(node) {
  if (Array.isArray(node)) return node.map(shapeOnly);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (SHAPE_ONLY.has(key) && 'properties' in node) continue;
    out[key] = shapeOnly(value);
  }
  return out;
}

const types = await compile(shapeOnly(schema), 'ShipkeepConfig', {
  bannerComment: header,
  additionalProperties: false,
  strictIndexSignatures: true,
  ignoreMinAndMaxItems: true,
  style: { singleQuote: true, printWidth: 100, trailingComma: 'all' },
});

const schemaModule = `${header}
/** JSON Schema 2020-12 of shipkeep.yml. */
export const shipkeepSchema = ${JSON.stringify(schema, null, 2)} as const;
`;

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'shipkeep-config.ts'), types);
await writeFile(join(outDir, 'schema.ts'), schemaModule);
console.log(`generated ${outDir}/shipkeep-config.ts and schema.ts`);
